// A study of the detail of the tiles by the direction of the view (agent 40, point 10 of the
// orchestrator: more detail far ahead of the player than behind him), measured before anything is
// built: no data of terrain_core depends on the view, only which tiles a client builds and keeps.
// The selections around a player (selectTiles, the rings of Unreal: LOD 0 to 64 m, 1 to 128 m, 2
// to 256 m, 3 to 512 m):
// - today: the same rings all around;
// - ahead: the tiles of LOD 3 whose middle lies within kSector degrees of the view (its half
//   field, kHalfField, and a margin on either side) split into their 4 tiles of LOD 2: 4 m cells
//   out to 512 m ahead (the teeth of the crests of the dunes at 300 to 500 m halved, point 11);
// - all around: LOD 2 out to 512 m everywhere (splitDistance {4, 8, 32}).
// For each: the tiles, their triangles and the time to generate them (tiles of LOD 2 and 3 of an
// erg with the planet file timed here, their median), and the worst case of a turn of 180 degrees
// in kTurnSeconds at 60 Hz: the tiles generated by kWorkers workers nearest first, kUploads shown
// per frame, a tile left only once the tiles covering it are shown (StreamManager): the frames
// where a tile of LOD 3 still shows within the field of view where a tile of LOD 2 is wanted (the
// detail pops in there when it comes), and the most of them. Printed for the report; the checks:
// every chunk within the view distance in exactly one tile of each selection, the 2:1 balance.
#include "coast_planet_support.hpp"

#include "test_assert.hpp"

#include "terrain/streaming/lod.hpp"

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdio>
#include <deque>
#include <map>
#include <numbers>
#include <set>
#include <vector>

namespace {

using terrain::ChunkCoord;
using terrain::TileKey;

constexpr double kHalfField = 45.0; // a horizontal field of view of 90 degrees
constexpr double kSector = kHalfField + 15.0;
constexpr double kTurnSeconds = 0.3;
constexpr double kFrame = 1.0 / 60.0;
constexpr int kWorkers = 2;   // TerrainWorld.h: WorkerThreads
constexpr int kUploads = 8;   // TerrainWorld.h: MaxTileUploadsPerFrame
constexpr int kTimed = 4;     // tiles of each LOD timed
constexpr double kErgX = -26'543'080.0, kErgZ = 5'119'222.0; // erg_etoile_150m

const terrain::LodParams kToday{{4, 8, 16}, 32};
const terrain::LodParams kAllAround{{4, 8, 32}, 32};

// The heading of the middle of a tile seen from the middle of the chunk of the player, degrees
// clockwise from -z, and how far it lies from the view.
double offView(const TileKey& t, ChunkCoord player, double yaw) {
    const double half = terrain::tileChunks(t.lod) / 2.0;
    const double dx = t.origin.x + half - (player.x + 0.5);
    const double dz = t.origin.z + half - (player.z + 0.5);
    const double heading = std::atan2(dx, -dz) * 180.0 / std::numbers::pi;
    return std::abs(std::remainder(heading - yaw, 360.0));
}

std::vector<TileKey> ahead(ChunkCoord player, double yaw) {
    std::vector<TileKey> out;
    for (const TileKey& t : terrain::selectTiles(player, kToday)) {
        if (t.lod == terrain::kMaxLod && offView(t, player, yaw) <= kSector) {
            const int h = terrain::tileChunks(t.lod - 1);
            for (int q = 0; q < 4; ++q) {
                out.push_back({{t.origin.x + (q & 1) * h, t.origin.z + (q >> 1) * h}, t.lod - 1});
            }
        } else {
            out.push_back(t);
        }
    }
    return out;
}

// Every chunk within the view distance in exactly one tile; tiles touching within one LOD.
void checkCover(const std::vector<TileKey>& tiles, ChunkCoord player) {
    std::map<std::pair<int, int>, int> lodOf;
    bool once = true;
    for (const TileKey& t : tiles) {
        const int n = terrain::tileChunks(t.lod);
        for (int dz = 0; dz < n; ++dz) {
            for (int dx = 0; dx < n; ++dx) {
                once = lodOf.emplace(std::pair{t.origin.x + dx, t.origin.z + dz}, t.lod).second &&
                       once;
            }
        }
    }
    bool covered = true, balanced = true;
    for (int dz = -kToday.viewDistance; dz <= kToday.viewDistance; ++dz) {
        for (int dx = -kToday.viewDistance; dx <= kToday.viewDistance; ++dx) {
            const auto it = lodOf.find({player.x + dx, player.z + dz});
            covered = covered && it != lodOf.end();
            for (const auto& [ex, ez] : {std::pair{1, 0}, {0, 1}, {1, 1}, {1, -1}}) {
                const auto next = lodOf.find({player.x + dx + ex, player.z + dz + ez});
                if (it != lodOf.end() && next != lodOf.end()) {
                    balanced = balanced && std::abs(it->second - next->second) <= 1;
                }
            }
        }
    }
    TEST_CHECK(once && covered && balanced);
}

// The median time to generate a tile of a LOD near the erg, ms, and its mean triangles.
std::pair<double, double> tileCost(int lod) {
    const ChunkCoord c = terrain::worldToChunk(kErgX, kErgZ);
    std::vector<double> ms;
    double triangles = 0.0;
    for (int q = 0; q < kTimed; ++q) {
        const TileKey key = terrain::tileContaining(
            {c.x + (q & 1) * terrain::tileChunks(lod) * 3, c.z + (q >> 1) * terrain::tileChunks(lod) * 3},
            lod);
        const auto start = std::chrono::steady_clock::now();
        const terrain::TileData data = coast_planet::tiles().generate({key, 0U, 0U});
        ms.push_back(std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() -
                                                               start).count());
        triangles += static_cast<double>(data.mesh.indices.size() / 3) / kTimed;
    }
    std::sort(ms.begin(), ms.end());
    return {ms[ms.size() / 2], triangles};
}

struct Turn {
    int frames = 0;       // frames with a tile of LOD 3 in the field where LOD 2 is wanted
    int most = 0;         // the most of such tiles in one frame
    double after = 0.0;   // seconds after the end of the turn until none
    int generated = 0;    // tiles generated during and after the turn
};

// A turn of 180 degrees from yaw 0 as the streaming would follow it (see the head of the file).
Turn turn(ChunkCoord player, const std::array<double, 4>& costMs) {
    std::set<std::pair<std::pair<int, int>, int>> shown;
    const auto id = [](const TileKey& t) { return std::pair{std::pair{t.origin.x, t.origin.z}, t.lod}; };
    for (const TileKey& t : ahead(player, 0.0)) {
        shown.insert(id(t));
    }
    std::deque<TileKey> queue;
    std::vector<std::pair<double, TileKey>> working; // finish time
    std::vector<TileKey> done;
    std::set<std::pair<std::pair<int, int>, int>> asked;
    Turn out;
    for (int f = 0; f < 600; ++f) {
        const double t = f * kFrame;
        const double yaw = std::min(1.0, t / kTurnSeconds) * 180.0;
        const std::vector<TileKey> wanted = ahead(player, yaw);
        for (const TileKey& w : wanted) {
            if (!shown.contains(id(w)) && asked.insert(id(w)).second) {
                queue.push_back(w);
            }
        }
        std::stable_sort(queue.begin(), queue.end(), [&](const TileKey& a, const TileKey& b) {
            return terrain::loadsBefore(a, b, player);
        });
        for (auto it = working.begin(); it != working.end();) {
            if (it->first <= t) {
                done.push_back(it->second);
                it = working.erase(it);
            } else {
                ++it;
            }
        }
        while (static_cast<int>(working.size()) < kWorkers && !queue.empty()) {
            working.emplace_back(t + costMs[static_cast<std::size_t>(queue.front().lod)] / 1000.0,
                                 queue.front());
            queue.pop_front();
            ++out.generated;
        }
        for (int u = 0; u < kUploads && !done.empty(); ++u) {
            shown.insert(id(done.front()));
            done.erase(done.begin());
        }
        int pending = 0;
        for (const TileKey& w : wanted) {
            if (w.lod == 2 && !shown.contains(id(w)) && offView(w, player, yaw) <= kHalfField) {
                ++pending;
            }
        }
        out.most = std::max(out.most, pending);
        out.frames += pending > 0 ? 1 : 0;
        if (pending > 0) {
            out.after = std::max(0.0, t + kFrame - kTurnSeconds);
        }
    }
    return out;
}

} // namespace

int main() {
    const ChunkCoord player = terrain::worldToChunk(kErgX, kErgZ);
    const std::vector<TileKey> today = terrain::selectTiles(player, kToday);
    const std::vector<TileKey> forward = ahead(player, 0.0);
    const std::vector<TileKey> around = terrain::selectTiles(player, kAllAround);
    for (const auto* tiles : {&today, &forward, &around}) {
        checkCover(*tiles, player);
    }
    std::array<double, 4> costMs{};
    std::array<double, 4> triangles{};
    for (int lod = 0; lod < terrain::kLodCount; ++lod) {
        std::tie(costMs[static_cast<std::size_t>(lod)], triangles[static_cast<std::size_t>(lod)]) =
            tileCost(lod);
        std::printf("a tile of LOD %d near erg_etoile_150m: %.2f ms to generate (median of %d), "
                    "%.0f triangles\n",
                    lod, costMs[static_cast<std::size_t>(lod)], kTimed,
                    triangles[static_cast<std::size_t>(lod)]);
    }
    const auto describe = [&](const char* name, const std::vector<TileKey>& tiles) {
        std::array<int, 4> n{};
        double ms = 0.0, tri = 0.0;
        for (const TileKey& t : tiles) {
            ++n[static_cast<std::size_t>(t.lod)];
            ms += costMs[static_cast<std::size_t>(t.lod)];
            tri += triangles[static_cast<std::size_t>(t.lod)];
        }
        std::printf("%s: %zu tiles (LOD 0 to 3: %d, %d, %d, %d), %.0f ms to generate them all on one "
                    "thread, about %.2f million triangles\n",
                    name, tiles.size(), n[0], n[1], n[2], n[3], ms, tri / 1e6);
    };
    describe("today", today);
    describe("ahead (LOD 2 to 512 m within 60 degrees of the view)", forward);
    describe("all around (LOD 2 to 512 m)", around);
    const Turn t = turn(player, costMs);
    std::printf("a turn of 180 degrees in %.1f s with ahead: %d tiles generated, a tile of LOD 3 "
                "in the field where LOD 2 is wanted during %d frames (%d at most in one frame), "
                "until %.2f s after the end of the turn\n",
                kTurnSeconds, t.generated, t.frames, t.most, t.after);
    TEST_CHECK(forward.size() > today.size() && around.size() > forward.size());
    return test::result();
}
