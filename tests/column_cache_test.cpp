namespace {

using terrain::TerrainTiles;
using terrain::TileData;
using terrain::TileRequest;

constexpr int kFew = 4;
constexpr int kMany = 12;
constexpr int kView = 10; // chunks
// Two blocks of shared columns in each shard: far fewer than the view needs.
constexpr std::size_t kSmall = 2 * terrain::tile::kColumnShards * terrain::tile::kSharedColumns;
constexpr std::uint64_t kOtherSeed = 0x5eed2;
constexpr double kK2X = 415'839.2;
constexpr double kK2Z = -11'414'503.0;
constexpr std::size_t kRockTiles = 20;
// bytes: 11.6 MB since the columns hold the seas of dunes (HeightSample, 72 bytes: agent 34) and
// the faces of the coasts (RockColumn, 304 bytes: agent 33), 377 bytes a column with its flag.
constexpr std::size_t kDefaultBound = 12'000'000;

void testShared() {
    using terrain::tile::sharedColumn;
    for (const int spacing : {1, 2, 4, 8}) {
        const std::int64_t side = 16 * spacing;
        TEST_CHECK(sharedColumn(0, 7 * spacing, spacing));
        TEST_CHECK(sharedColumn(spacing, 7 * spacing, spacing));
        TEST_CHECK(sharedColumn(15 * spacing, 7 * spacing, spacing));
        TEST_CHECK(sharedColumn(-spacing, 7 * spacing - side, spacing));
        TEST_CHECK(sharedColumn(7 * spacing - side, -2 * side, spacing));
        TEST_CHECK(!sharedColumn(7 * spacing, 7 * spacing, spacing));
        TEST_CHECK(!sharedColumn(2 * spacing - side, 14 * spacing - 3 * side, spacing));
        TEST_CHECK(spacing == 1 || !sharedColumn(1, 1, spacing)); // not on the lattice
    }
}

// The tiles of requests generated by threads, in the order of order.
std::vector<TileData> generate(const TerrainTiles& tiles, const std::vector<TileRequest>& requests,
                               const std::vector<std::size_t>& order, int threads) {
    std::vector<TileData> out(requests.size());
    std::atomic<std::size_t> next{0};
    std::vector<std::thread> pool;
    for (int t = 0; t < threads; ++t) {
        pool.emplace_back([&] {
            for (std::size_t n; (n = next++) < order.size();) {
                out[order[n]] = tiles.generate(requests[order[n]]);
            }
        });
    }
    for (std::thread& t : pool) {
        t.join();
    }
    return out;
}

// 0, 1, ..., count - 1, every stride-th first (stride made prime with count: each once).
std::vector<std::size_t> orderOf(std::size_t count, std::size_t stride) {
    while (std::gcd(stride, count) != 1) {
        ++stride;
    }
    std::vector<std::size_t> order;
    for (std::size_t n = 0; n < count; ++n) {
        order.push_back((n * stride) % count);
    }
    return order;
}

std::size_t differing(const std::vector<TileData>& a, const std::vector<TileData>& b) {
    std::size_t wrong = 0;
    for (std::size_t i = 0; i < a.size(); ++i) {
        wrong += a[i] == b[i] ? 0 : 1;
    }
    return wrong;
}

// The tiles of view in a world made by make (columnCache: its cache) against cold, those of the
// world without the cache: in order, by kFew threads, then by kMany in a fresh world.
template <typename Make>
void testBits(const char* what, const Make& make, const std::vector<TileRequest>& view,
              const std::vector<TileData>& cold, std::size_t rockLeast) {
    const std::size_t rockTiles = static_cast<std::size_t>(
        std::count_if(cold.begin(), cold.end(), [](const TileData& t) { return !t.rock.empty(); }));
    const auto cached = make(terrain::kColumnCacheColumns);
    const std::size_t inOrder =
        differing(cold, generate(*cached, view, orderOf(view.size(), 1), 1));
    const std::size_t few = differing(cold, generate(*cached, view, orderOf(view.size(), 7), kFew));
    const auto fresh = make(terrain::kColumnCacheColumns);
    const std::size_t many =
        differing(cold, generate(*fresh, view, orderOf(view.size(), 11), kMany));
    const terrain::ColumnCacheStats s = cached->columnCache();
    const terrain::ColumnCacheStats m = fresh->columnCache();
    std::printf("%s: %zu tiles of LOD 0 to 3 (%zu with rock): %zu, %zu and %zu differ from those "
                "without the cache, in order, by %d and by %d threads; %.0f%% and %.0f%% of the "
                "shared columns found; %llu of %llu locks waited for with %d threads\n",
                what, view.size(), rockTiles, inOrder, few, many, kFew, kMany,
                100.0 * static_cast<double>(s.hits) / static_cast<double>(s.lookups),
                100.0 * static_cast<double>(m.hits) / static_cast<double>(m.lookups),
                static_cast<unsigned long long>(m.contended),
                static_cast<unsigned long long>(m.locks), kMany);
    TEST_CHECK(view.size() >= 100 && rockTiles >= rockLeast);
    TEST_CHECK(inOrder == 0 && few == 0 && many == 0);
    TEST_CHECK(s.hits > 0 && m.hits > 0);
}

void testWorlds(const falls::World& w, const std::vector<TileRequest>& view,
                const std::vector<TileData>& cold) {
    const TerrainTiles coldOther(kOtherSeed, {}, {}, std::nullopt, golden::kSmallPlanet, nullptr,
                                 true, 0);
    const std::vector<TileData> other = generate(coldOther, view, orderOf(view.size(), 1), 1);
    // Both worlds at once, the same keys in turn.
    const TerrainTiles a(terrain::kDefaultWorldSeed, {}, {}, std::nullopt, golden::kSmallPlanet,
                         w.hydrology);
    const TerrainTiles b(kOtherSeed, {}, {}, std::nullopt, golden::kSmallPlanet);
    std::vector<TileData> fromA(view.size());
    std::vector<TileData> fromB(view.size());
    std::atomic<std::size_t> next{0};
    std::vector<std::thread> pool;
    for (int t = 0; t < kFew; ++t) {
        pool.emplace_back([&] {
            for (std::size_t n; (n = next++) < 2 * view.size();) {
                const std::size_t i = n / 2;
                (n % 2 == 0 ? fromA[i] : fromB[i]) = (n % 2 == 0 ? a : b).generate(view[i]);
            }
        });
    }
    for (std::thread& t : pool) {
        t.join();
    }
    // A world made again with the other seed after the first (Terrain.Seed).
    std::optional<TerrainTiles> world;
    world.emplace(terrain::kDefaultWorldSeed, terrain::HeightfieldParams{},
                  terrain::EcologyParams{}, std::nullopt, golden::kSmallPlanet, w.hydrology);
    (void)generate(*world, view, orderOf(view.size(), 1), kFew);
    world.reset();
    world.emplace(kOtherSeed, terrain::HeightfieldParams{}, terrain::EcologyParams{}, std::nullopt,
                  golden::kSmallPlanet);
    const std::size_t remade = differing(other, generate(*world, view, orderOf(view.size(), 3), 1));
    std::printf("two worlds of two seeds: %zu and %zu tiles differ from those of their seed "
                "without the cache; the world made again with the other seed, %zu\n",
                differing(cold, fromA), differing(other, fromB), remade);
    TEST_CHECK(differing(cold, fromA) == 0 && differing(other, fromB) == 0 && remade == 0);
    TEST_CHECK(differing(cold, other) == view.size()); // the two seeds give other tiles
}

// The same edits on a world: a block added, a sphere dug, a plant added and one removed.
void edit(TerrainTiles& tiles, double x, double z, const std::vector<TileData>& cold) {
    const auto y = static_cast<std::int32_t>(std::floor(tiles.heightfield().heightAt(x, z)));
    const auto bx = static_cast<std::int32_t>(std::floor(x));
    const auto bz = static_cast<std::int32_t>(std::floor(z));
    tiles.setBlock({bx + 3, y + 1, bz}, terrain::BlockEdit::Added);
    tiles.applyEdit({terrain::EditShape::Sphere,
                     terrain::EditMode::Remove,
                     {bx, y, bz + 4},
                     {},
                     static_cast<std::uint16_t>(5 * 16)});
    tiles.addPlant({terrain::PlantType::Tree, x + 6.5, z - 5.5,
                    tiles.heightfield().heightAt(x + 6.5, z - 5.5), 1.0f, 0.0f});
    for (const TileData& t : cold) {
        if (!t.plants.empty()) {
            tiles.removePlant(t.plants.front());
            break;
        }
    }
}

void testEdits(const falls::World& w, const std::vector<TileRequest>& view, double x, double z,
               const std::vector<TileData>& cold) {
    TerrainTiles cached(terrain::kDefaultWorldSeed, {}, {}, std::nullopt, golden::kSmallPlanet,
                        w.hydrology);
    (void)generate(cached, view, orderOf(view.size(), 1), kFew); // the cache holds the columns
    const terrain::ColumnCacheStats before = cached.columnCache();
    TerrainTiles plain(terrain::kDefaultWorldSeed, {}, {}, std::nullopt, golden::kSmallPlanet,
                       w.hydrology, true, 0);
    edit(cached, x, z, cold);
    edit(plain, x, z, cold);
    const std::vector<TileData> expected = generate(plain, view, orderOf(view.size(), 1), kFew);
    const std::vector<TileData> got = generate(cached, view, orderOf(view.size(), 5), kFew);
    const std::size_t changed = differing(cold, expected);
    std::printf("edits once the cache holds %zu columns: %zu tiles changed by them, %zu differ "
                "from those of the world without the cache\n",
                before.columns, changed, differing(expected, got));
    TEST_CHECK(before.columns > 0 && changed > 0);
    TEST_CHECK(differing(expected, got) == 0);
}

void testMemory(const falls::World& w, const std::vector<TileRequest>& view,
                const std::vector<TileData>& cold) {
    const TerrainTiles small(terrain::kDefaultWorldSeed, {}, {}, std::nullopt, golden::kSmallPlanet,
                             w.hydrology, true, kSmall);
    const std::size_t wrong =
        differing(cold, generate(small, view, orderOf(view.size(), 13), kFew));
    const terrain::ColumnCacheStats s = small.columnCache();
    const TerrainTiles large(terrain::kDefaultWorldSeed, {}, {}, std::nullopt, golden::kSmallPlanet,
                             w.hydrology);
    std::printf("a cache of %zu columns: %zu held, %.2f MB of %.2f MB at most, %zu tiles differ; "
                "the default one, %.1f MB at most\n",
                s.capacity, s.columns, static_cast<double>(s.bytes) * 1e-6,
                static_cast<double>(s.bytesBound) * 1e-6, wrong,
                static_cast<double>(large.columnCache().bytesBound) * 1e-6);
    TEST_CHECK(s.capacity == kSmall && s.columns <= kSmall && s.columns > 0);
    TEST_CHECK(s.bytes <= s.bytesBound && wrong == 0);
    TEST_CHECK(large.columnCache().bytesBound <= kDefaultBound);
}

} // namespace

int main() {
    testShared();
    const falls::World w = falls::makeWorld();
    falls::Reaches reaches(*w.hydrology);
    const terrain::RiverReach& reach = reaches[falls::steepReaches(w, reaches).front()];
    const terrain::RiverPoint& p = reach.points[reach.points.size() / 2];
    terrain::LodParams lod;
    lod.viewDistance = kView;
    const std::vector<TileRequest> view =
        terrain::tileRequests(terrain::selectTiles(terrain::worldToChunk(p.x, p.z), lod));
    const auto falls = [&w](std::size_t cache) {
        return std::make_unique<TerrainTiles>(
            terrain::kDefaultWorldSeed, terrain::HeightfieldParams{}, terrain::EcologyParams{},
            std::nullopt, golden::kSmallPlanet, w.hydrology, true, cache);
    };
    const std::vector<TileData> cold = generate(*falls(0), view, orderOf(view.size(), 1), kFew);
    testBits("the falls", falls, view, cold, 0);
    // The walls of the K2 (rock_walk_test): rock tiles, the rings of their sides.
    const auto k2 = [](std::size_t cache) {
        return std::make_unique<TerrainTiles>(
            terrain::kDefaultWorldSeed, terrain::HeightfieldParams{}, terrain::EcologyParams{},
            std::nullopt, terrain::WorldSize{}, nullptr, true, cache);
    };
    const std::vector<TileRequest> walls =
        terrain::tileRequests(terrain::selectTiles(terrain::worldToChunk(kK2X, kK2Z), lod));
    testBits("the K2", k2, walls, generate(*k2(0), walls, orderOf(walls.size(), 1), kFew),
             kRockTiles);
    testWorlds(w, view, cold);
    testEdits(w, view, p.x, p.z, cold);
    testMemory(w, view, cold);
    return test::result();
}
