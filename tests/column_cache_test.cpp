// The cache of the columns neighboring tiles share (src/streaming/column_cache.hpp), phase 12A.
//   - Shared columns: those on the two outer rows of the sides of their tile (sharedColumn),
//     at every LOD, on either side of 0.
//   - Bits: the tiles of a view near a fall of the small world (LOD 0 to 3, rock tiles with
//     their rings among them) are those of the same world without the cache (columnCache 0),
//     bit for bit, generated in order, then by kFew and by kMany threads in other orders; the
//     cache found columns there.
//   - Worlds: the tiles of two worlds of two seeds in one process, generated in turn by kFew
//     threads at the same keys, are those of their seed without the cache; a world made again
//     with the other seed (as Terrain.Seed does) takes nothing from the first.
//   - Edits: blocks, volumes and plants made once the cache holds the columns: the tiles are
//     those of a world without the cache with the same edits (the edits never reach the
//     columns, so the cache never forgets anything for them).
//   - Memory: a cache of kSmall columns holds kSmall at most, its memory within its bound, and
//     the tiles stay the same while it forgets its oldest columns; the default one within
//     kDefaultBound bytes.
#include "column_cache.hpp"
#include "falls_support.hpp"

#include "terrain/streaming/lod.hpp"
