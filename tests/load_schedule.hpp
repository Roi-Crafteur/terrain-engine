#pragma once

// The load of the tiles around a place, simulated from the cost of each tile (agent 38): to
// compare the orders of the loads and the number of workers before changing the streaming. Used
// by unreal_loading_bench --schedule, tested by load_schedule_test.

#include "terrain/streaming/lod.hpp"
#include "terrain/streaming/stream_manager.hpp"
#include "terrain/streaming/terrain_tiles.hpp"

#include <cstddef>
#include <span>
#include <string>
#include <vector>

namespace load_schedule {

struct Params {
    int workers = 2;
    std::size_t uploadsPerFrame = 8;
    double frameSeconds = 1.0 / 60.0;
};

// The tiles generated in their order by `workers` workers, each taking the next tile as soon as
// it is free (the queue of StreamManager), then shown at the updates, one per frame from the
// start: each update shows up to uploadsPerFrame of the tiles generated by then, in their order
// (StreamManager::integrate). Returns the instant each tile is shown, seconds. Throws
// std::invalid_argument for workers or uploadsPerFrame below 1, a frame of 0 s or less, or a
// negative cost.
[[nodiscard]] std::vector<double> simulate(std::span<const double> costs, const Params& params);

// A tile of a simulated load: its request, its distance to the chunk of the player, its cost.
struct Tile {
    terrain::TileRequest request;
    int distanceChunks = 0;
    double cost = 0.0; // seconds
};

// The instant the last tile closer than `reach` chunks is shown (every tile: reach < 0), among
// the tiles whose instants are given (same order); -1 for no such tile.
[[nodiscard]] double lastShown(std::span<const Tile> tiles, std::span<const double> shown,
                               int reach);

struct Place {
    double x = 0.0;
    double z = 0.0;
};

// The rings of the coarse stage: LOD 0 within 2 chunks, LOD 1 within 4, LOD 2 within 8.
inline constexpr std::array<int, terrain::kMaxLod> kCoarseSplit = {2, 4, 8};

// For each place: the tiles of the selection (the rings of params) and of the coarse stage,
// generated one at a time on this thread to measure their costs, then the loads simulated for 2,
// 4, 8 and 16 workers and 8 or 32 updates per frame, in the order of today (nearest first) and
// with the coarse stage first (its tiles, then the tiles of the selection it does not hold). One
// line per case, for the bench.
[[nodiscard]] std::vector<std::string> report(const terrain::TerrainTiles& tiles,
                                              const terrain::StreamParams& params,
                                              std::span<const Place> places);

} // namespace load_schedule
